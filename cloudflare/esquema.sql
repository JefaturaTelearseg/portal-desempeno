CREATE TABLE IF NOT EXISTS config (clave TEXT PRIMARY KEY, valor TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS evaluaciones (semana TEXT NOT NULL, op TEXT NOT NULL, datos TEXT NOT NULL, por TEXT, creado TEXT, PRIMARY KEY (semana, op));
CREATE TABLE IF NOT EXISTS accesos (id INTEGER PRIMARY KEY AUTOINCREMENT, fecha TEXT, correo TEXT, rol TEXT, accion TEXT, ip TEXT, lugar TEXT);
CREATE TABLE IF NOT EXISTS intentos (clave TEXT PRIMARY KEY, n INTEGER, hasta INTEGER);
CREATE TABLE IF NOT EXISTS respaldos (id INTEGER PRIMARY KEY AUTOINCREMENT, fecha TEXT, valor TEXT);
